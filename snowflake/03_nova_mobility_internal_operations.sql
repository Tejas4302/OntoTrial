CREATE OR REPLACE VIEW NOVA_MOBILITY_OPERATIONS AS
SELECT
  p.PO_ID,
  p.PO_DATE,
  p.PROMISED_DATE,
  p.STATUS PO_STATUS,
  p.ORDER_QTY,
  p.RECEIVED_QTY,
  p.PO_VALUE_USD,
  s.SUPPLIER_ID,
  s.SUPPLIER_NAME,
  s.ORIGIN_ISO,
  s.ORIGIN_COUNTRY,
  s.SUPPLIER_TIER,
  s.CATEGORY,
  s.CRITICALITY SUPPLIER_CRITICALITY,
  m.MATERIAL_ID,
  m.MATERIAL_NAME,
  m.HS4_CODE,
  m.COMMODITY_GROUP,
  m.CRITICALITY MATERIAL_CRITICALITY,
  p.PLANT_NAME,
  sh.SHIPMENT_ID,
  sh.TRANSPORT_MODE,
  sh.ETA_DATE,
  sh.SHIPMENT_STATUS,
  inv.ON_HAND_QTY,
  inv.SAFETY_STOCK_QTY,
  inv.DAILY_DEMAND_QTY,
  inv.DAYS_OF_COVER,
  inv.SNAPSHOT_DATE
FROM NOVA_PURCHASE_ORDERS p
JOIN NOVA_SUPPLIER_MASTER s USING (SUPPLIER_ID)
JOIN NOVA_MATERIAL_MASTER m USING (MATERIAL_ID)
LEFT JOIN NOVA_SHIPMENTS sh USING (PO_ID,SUPPLIER_ID,MATERIAL_ID)
LEFT JOIN NOVA_INVENTORY inv USING (MATERIAL_ID,PLANT_NAME);

CREATE OR REPLACE VIEW NOVA_MOBILITY_RISK_ENRICHED AS
WITH ext AS (
  SELECT
    ORIGIN_ISO,
    HS4_STR,
    MAX(ORIGIN_COUNTRY) MARKETPLACE_ORIGIN_COUNTRY,
    SUM(NOMINAL_TRADE_VALUE) INDIA_IMPORT_VALUE_USD,
    SUM(NOMINAL_BY_SEA)/NULLIF(SUM(NOMINAL_TRADE_VALUE),0)*100 MARKET_SEA_DEPENDENCY_PCT,
    SUM(NOMINAL_BY_AIR)/NULLIF(SUM(NOMINAL_TRADE_VALUE),0)*100 MARKET_AIR_DEPENDENCY_PCT,
    MAX(IFF(WEATHER_DATA_AVAILABLE,1,0)) WEATHER_DATA_AVAILABLE,
    MAX(WEATHER_RISK_SCORE) WEATHER_RISK_SCORE,
    MAX(WEATHER_RISK_LEVEL) WEATHER_RISK_LEVEL,
    MAX(AFFECTED_LOCATION_PCT) AFFECTED_LOCATION_PCT
  FROM INDIA_TRADE_RISK_ENRICHED
  WHERE TRADE_YEAR=2026
    AND TRADE_DIRECTION='IMPORT'
  GROUP BY ORIGIN_ISO,HS4_STR
)
SELECT
  o.*,
  ext.INDIA_IMPORT_VALUE_USD,
  ext.MARKET_SEA_DEPENDENCY_PCT,
  ext.MARKET_AIR_DEPENDENCY_PCT,
  IFF(ext.WEATHER_DATA_AVAILABLE=1,TRUE,FALSE) WEATHER_DATA_AVAILABLE,
  ext.WEATHER_RISK_SCORE,
  ext.WEATHER_RISK_LEVEL,
  ext.AFFECTED_LOCATION_PCT,
  IFF(ext.ORIGIN_ISO IS NULL,FALSE,TRUE) MARKETPLACE_MATCH_AVAILABLE,
  CASE
    WHEN o.DAYS_OF_COVER < 7 THEN 'HIGH'
    WHEN o.DAYS_OF_COVER < 14 THEN 'MEDIUM'
    ELSE 'LOW'
  END INVENTORY_RISK_LEVEL,
  CASE
    WHEN o.PO_STATUS='DELAYED' AND o.DAYS_OF_COVER < 7 THEN 'HIGH'
    WHEN o.PO_STATUS IN ('DELAYED','PARTIALLY_RECEIVED') OR o.DAYS_OF_COVER < 14 THEN 'MEDIUM'
    ELSE 'LOW'
  END OPERATIONAL_RISK_LEVEL
FROM NOVA_MOBILITY_OPERATIONS o
LEFT JOIN ext
  ON ext.ORIGIN_ISO=o.ORIGIN_ISO
 AND LPAD(ext.HS4_STR::VARCHAR,4,'0')=LPAD(o.HS4_CODE::VARCHAR,4,'0');

