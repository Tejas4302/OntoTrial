INSERT INTO NOVA_PURCHASE_ORDERS
WITH generated_po_rows AS (
    SELECT
      SEQ4()+1 N
    FROM TABLE(GENERATOR(ROWCOUNT=>32))
),
base AS (
    SELECT
      N,
      CASE MOD(N-1,8)
        WHEN 0 THEN 'SUP-NV-001' WHEN 1 THEN 'SUP-NV-002'
        WHEN 2 THEN 'SUP-NV-003' WHEN 3 THEN 'SUP-NV-004'
        WHEN 4 THEN 'SUP-NV-005' WHEN 5 THEN 'SUP-NV-006'
        WHEN 6 THEN 'SUP-NV-007' ELSE 'SUP-NV-008' END SUPPLIER_ID,
      CASE MOD(N-1,8)
        WHEN 0 THEN 'MAT-BAT-001' WHEN 1 THEN 'MAT-INV-001'
        WHEN 2 THEN 'MAT-MOT-001' WHEN 3 THEN 'MAT-CHP-001'
        WHEN 4 THEN 'MAT-SNS-001' WHEN 5 THEN 'MAT-CON-001'
        WHEN 6 THEN 'MAT-THM-001' ELSE 'MAT-PMP-001' END MATERIAL_ID,
      40 + MOD(N*31,260) ORDER_QTY
    FROM generated_po_rows
)
SELECT
  'PO-NV-'||LPAD(N::VARCHAR,4,'0'),
  DATEADD('day',-MOD(N*3,70),'2026-09-22'::DATE),
  b.SUPPLIER_ID,
  b.MATERIAL_ID,
  m.PRIMARY_PLANT,
  ORDER_QTY,
  CASE
    WHEN MOD(N,7)=0 THEN FLOOR(ORDER_QTY*0.35)
    WHEN MOD(N,5)=0 THEN FLOOR(ORDER_QTY*0.70)
    ELSE ORDER_QTY
  END,
  m.UNIT_COST_USD,
  ROUND(ORDER_QTY*m.UNIT_COST_USD,2),
  DATEADD('day',7+MOD(N*5,38),'2026-09-22'::DATE),
  CASE
    WHEN MOD(N,7)=0 THEN 'DELAYED'
    WHEN MOD(N,5)=0 THEN 'PARTIALLY_RECEIVED'
    WHEN MOD(N,3)=0 THEN 'IN_TRANSIT'
    ELSE 'OPEN'
  END
FROM base b
JOIN NOVA_MATERIAL_MASTER m USING (MATERIAL_ID);

